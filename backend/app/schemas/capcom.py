"""
CAPCOM AI Assistant Request & Response Schemas
Mission Forge — Phase 5
"""

from datetime import datetime, timezone
from typing import Dict, List, Optional
from pydantic import BaseModel, Field

from backend.app.fdir.telemetry import TelemetryReading

CAPCOM_SAFETY_DISCLAIMER = (
    "ADVISORY SIMULATION ONLY: CAPCOM AI is an advisory systems assistant. "
    "It is not NASA-certified, does not control real spacecraft hardware, "
    "and does not replace a designated human Flight Director."
)


class VerifiedFact(BaseModel):
    """A statement verified directly against authoritative system state or source feeds."""
    statement: str
    source: str
    citation: str


class FormattedCalculation(BaseModel):
    """Deterministic backend engineering computation with explicit units and formula."""
    name: str
    value: float
    unit: str
    formula_reference: str


class AIRecommendation(BaseModel):
    """Advisory engineering recommendation generated by the assistant."""
    recommendation: str
    engineering_rationale: str
    priority: str = "MEDIUM"  # "HIGH", "MEDIUM", "LOW"


class FDIRFindingSummary(BaseModel):
    """Immutable summary of an active deterministic FDIR finding."""
    rule_id: str
    severity: str
    affected_subsystem: str
    explanation: str
    triage_guidance: str


class CAPCOMRequest(BaseModel):
    """Inbound query to the CAPCOM AI assistant."""
    query: str = Field(..., min_length=2, max_length=1000, description="Natural language query")
    room_id: Optional[str] = Field(None, description="CDF Room UUID for state grounding")
    telemetry_readings: Optional[List[TelemetryReading]] = Field(
        None, description="Optional telemetry readings for FDIR cross-examination"
    )


class CAPCOMResponse(BaseModel):
    """Structured, schema-validated response from CAPCOM AI."""
    query: str
    verified_source_facts: List[VerifiedFact]
    deterministic_calculations: Dict[str, FormattedCalculation]
    ai_recommendations: List[AIRecommendation]
    unknown_or_insufficient_data: List[str]
    fdir_active_findings: List[FDIRFindingSummary]
    safety_disclaimer: str = CAPCOM_SAFETY_DISCLAIMER
    model_name: str
    is_live_generation: bool
    generation_timestamp: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))
