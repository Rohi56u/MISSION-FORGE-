"""
Deterministic Power & Thermal Physics
Implements the Inverse-Square Law for Solar Irradiance, MMRTG Radioisotope Decay,
and Spacecraft Power Budget Margin Analysis with verified citations.
"""

import math
from typing import Dict, Any
from backend.app.physics.constants import (
    SOLAR_CONSTANT_1AU,
    PU238_HALF_LIFE_YEARS,
    TYPICAL_THERMOCOUPLE_DECAY_RATE,
)


def solar_irradiance(distance_au: float) -> float:
    """
    Calculates solar flux (irradiance) at distance r using Inverse-Square Law.

    Formula:
        S(r) = S_0 * (1 AU / r)^2

    Reference:
        S_0 = 1361.0 W/m^2 (Nominal Total Solar Irradiance per Kopp & Lean 2011;
        reaffirmed by IAU 2015 Resolution B3. Note: ASTM E490-00a historically
        used 1366.1 W/m^2; modern satellite radiometry establishes 1361.0 W/m^2).

    Args:
        distance_au: Heliocentric distance in Astronomical Units (AU) (> 0).

    Returns:
        Solar flux in Watts per square meter (W/m^2).

    Raises:
        ValueError: If distance_au <= 0.
    """
    if distance_au <= 0.0:
        raise ValueError(
            f"Heliocentric distance must be strictly positive, got {distance_au} AU."
        )

    return float(SOLAR_CONSTANT_1AU / (distance_au ** 2))


def solar_array_power(
    distance_au: float,
    area_m2: float,
    efficiency: float = 0.30,
    incidence_angle_deg: float = 0.0,
) -> float:
    """
    Calculates electrical power generated by a planar photovoltaic solar array.

    Formula:
        P = S(r) * A * eta * cos(theta)

    Args:
        distance_au: Distance from Sun in AU (> 0).
        area_m2: Active photovoltaic cell area in m^2 (> 0).
        efficiency: Solar cell conversion efficiency (0 < efficiency <= 1.0,
            typically 0.28-0.34 for modern triple-junction GaAs cells).
        incidence_angle_deg: Sun incidence angle relative to array normal
            in degrees (0 to 90).

    Returns:
        Electrical power generated in Watts.

    Raises:
        ValueError: On invalid physical inputs.
    """
    if area_m2 <= 0.0:
        raise ValueError(f"Array area must be strictly positive, got {area_m2} m^2.")
    if not (0.0 < efficiency <= 1.0):
        raise ValueError(
            f"Cell efficiency must be between 0 and 1, got {efficiency}."
        )
    if not (0.0 <= incidence_angle_deg <= 90.0):
        raise ValueError(
            f"Incidence angle must be between 0 and 90 degrees, got {incidence_angle_deg}."
        )

    flux = solar_irradiance(distance_au)
    cos_theta = math.cos(math.radians(incidence_angle_deg))
    return float(flux * area_m2 * efficiency * cos_theta)


def mmrtg_power_at_time(
    p_bol_w: float = 110.0,
    time_years: float = 0.0,
    annual_thermocouple_decay: float = TYPICAL_THERMOCOUPLE_DECAY_RATE,
) -> float:
    """
    Models electrical power output of a Multi-Mission Radioisotope
    Thermoelectric Generator (MMRTG).

    The power decline is driven by two distinct physical mechanisms:
      1. Radioactive decay of the Plutonium-238 heat source (T_half = 87.7 years,
         fractional loss ~0.787%/year).
      2. Silicon-Germanium / Lead-Telluride thermocouple material degradation
         (empirical ~0.8%/year observed on MSL Curiosity).

    Engineering Model & Limitations:
        P(t) = P_BOL * exp(-ln(2) * t / T_half) * (1 - decay_tc)^t
        This is an empirical engineering planning model. It assumes constant
        cold-junction temperature and nominal load conditions. Flight experience
        shows early-mission degradation can be higher (~1.2%/yr) before settling.

    Args:
        p_bol_w: Beginning-of-Life (BOL) electrical power in Watts
            (default: 110 W for standard NASA MMRTG).
        time_years: Mission elapsed time in years (>= 0).
        annual_thermocouple_decay: Fractional degradation rate of thermoelectric
            couples per year (default: 0.008 = 0.8%/year).

    Returns:
        Electrical power output in Watts at mission elapsed time t.

    Raises:
        ValueError: If inputs are negative or thermocouple decay is not in [0, 1).
    """
    if p_bol_w < 0.0:
        raise ValueError(
            f"Beginning of life power must be non-negative, got {p_bol_w} W."
        )
    if time_years < 0.0:
        raise ValueError(
            f"Time elapsed cannot be negative, got {time_years} years."
        )
    if not (0.0 <= annual_thermocouple_decay < 1.0):
        raise ValueError(
            f"Thermocouple decay rate must be in [0, 1), got {annual_thermocouple_decay}."
        )

    # Isotope radioactive decay factor
    lambda_decay = math.log(2.0) / PU238_HALF_LIFE_YEARS
    isotope_factor = math.exp(-lambda_decay * time_years)

    # Thermocouple material degradation factor
    thermocouple_factor = (1.0 - annual_thermocouple_decay) ** time_years

    return float(p_bol_w * isotope_factor * thermocouple_factor)


def mmrtg_decay_breakdown(
    p_bol_w: float = 110.0,
    time_years: float = 0.0,
    annual_thermocouple_decay: float = TYPICAL_THERMOCOUPLE_DECAY_RATE,
) -> Dict[str, Any]:
    """
    Decomposes MMRTG electrical power output into its two distinct physical drivers:
      1. Pu-238 isotopic radioactive decay (T_half = 87.7 yr, lambda = 0.007904 yr^-1).
         Governs thermal heat output: Q_th(t) = Q_0 * exp(-lambda * t).
      2. Thermocouple solid-state degradation (empirical planning rate, nominal ~0.8%/yr).
         Governs conversion efficiency: eta(t) = eta_0 * (1 - delta_tc)^t.

    Returns:
        Structured breakdown separating nuclear physics from empirical material degradation.
    """
    if p_bol_w < 0.0:
        raise ValueError(f"Beginning of life power must be non-negative, got {p_bol_w} W.")
    if time_years < 0.0:
        raise ValueError(f"Time elapsed cannot be negative, got {time_years} years.")
    if not (0.0 <= annual_thermocouple_decay < 1.0):
        raise ValueError(
            f"Thermocouple decay rate must be in [0, 1), got {annual_thermocouple_decay}."
        )

    lambda_decay = math.log(2.0) / PU238_HALF_LIFE_YEARS
    isotope_factor = math.exp(-lambda_decay * time_years)
    thermocouple_factor = (1.0 - annual_thermocouple_decay) ** time_years
    combined_factor = isotope_factor * thermocouple_factor
    power_w = p_bol_w * combined_factor

    # Nominal MMRTG thermal beginning-of-life power is ~2000 W thermal (~5.5% efficiency)
    thermal_bol_w = 2000.0 if p_bol_w == 110.0 else (p_bol_w / 0.055)
    thermal_power_w = thermal_bol_w * isotope_factor

    degradation_pct = (
        ((p_bol_w - power_w) / p_bol_w * 100.0) if p_bol_w > 0.0 else 0.0
    )

    return {
        "initial_power_bol_w": round(p_bol_w, 2),
        "mission_time_years": round(time_years, 3),
        "annual_thermocouple_degradation_rate": annual_thermocouple_decay,
        "pu238_isotope_fraction_remaining": round(isotope_factor, 5),
        "thermocouple_fraction_remaining": round(thermocouple_factor, 5),
        "combined_fraction_remaining": round(combined_factor, 5),
        "power_output_w": round(power_w, 2),
        "total_degradation_percent": round(degradation_pct, 2),
        "thermal_power_w": round(thermal_power_w, 1),
        "notes": (
            "Pu-238 half-life decay is exact nuclear physics. "
            "Thermocouple degradation is an empirical engineering scenario (MSL/Perseverance data)."
        ),
    }


def evaluate_power_balance(
    power_generated_w: float,
    power_consumed_w: float,
    min_margin_percent: float = 15.0,
) -> Dict[str, Any]:
    """
    Evaluates power margin and detects brownout / deficit conditions.

    Standards Note:
        Recommended power margins evolve by project lifecycle phase per NASA
        Systems Engineering Handbook (NASA/SP-2016-6105 Rev 2, Section 6.7)
        and GSFC-STD-1000 ("Gold Rules", Rule 1.05/1.06: 15-20% at Preliminary
        Design Review). In Mission Forge, min_margin_percent is a configurable
        engineering design assumption (default 15.0%).
        (Note: NASA-HDBK-4008 is a PLD handbook, not a power margin standard).

    Args:
        power_generated_w: Total power generated by solar/MMRTG in Watts.
        power_consumed_w: Total power consumed by spacecraft systems in Watts.
        min_margin_percent: Minimum acceptable margin percentage.

    Returns:
        Dictionary detailing power margin, status, and sufficiency.
    """
    margin_w = power_generated_w - power_consumed_w
    margin_percent = (
        (margin_w / power_consumed_w * 100.0) if power_consumed_w > 0 else 100.0
    )
    is_sufficient = margin_w >= 0 and margin_percent >= min_margin_percent

    severity = "NOMINAL"
    if margin_w < 0:
        severity = "CRITICAL"
    elif margin_percent < min_margin_percent:
        severity = "WARNING"

    return {
        "power_generated_w": round(power_generated_w, 2),
        "power_consumed_w": round(power_consumed_w, 2),
        "margin_w": round(margin_w, 2),
        "margin_percent": round(margin_percent, 1),
        "min_required_margin_percent": min_margin_percent,
        "is_sufficient": is_sufficient,
        "status": severity,
    }
